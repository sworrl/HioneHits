    private val glyphs: Map<Char, Glyph> = parse(SRC)

    private fun parse(src: String): Map<Char, Glyph> {
        val out = HashMap<Char, Glyph>()
        var cur: Char? = null
        var rows = ArrayList<String>()
        fun flush() {
            val c = cur ?: return
            val bits = IntArray(HEIGHT)
            var maxCol = -1
            rows.take(HEIGHT).forEachIndexed { r, line ->
                var v = 0
                line.forEachIndexed { x, ch ->
                    if (ch == '#') { v = v or (1 shl x); if (x > maxCol) maxCol = x }
                }
                bits[r] = v
            }
            // Blank glyphs (space) keep their drawn width so spacing is still under our control.
            val w = if (maxCol < 0) (rows.firstOrNull()?.length ?: 3).coerceAtMost(3) else maxCol + 1
            out[c] = Glyph(w, bits)
        }
        for (raw in src.lines()) {
            if (raw.startsWith("@") && raw.length >= 2) {
                flush()
                cur = raw[1]
                rows = ArrayList()
            } else if (cur != null && raw.isNotEmpty()) {
                rows.add(raw)
            }
        }
        flush()
        return out
    }

    fun glyph(c: Char): Glyph? = glyphs[c]

    /** Advance in pixels, one pixel of spacing included. Unknown chars are measured by the caller. */
    fun advance(c: Char): Int = glyphs[c]?.let { it.width + 1 } ?: -1

    /** Folds the common Latin accents onto plain letters so "Bjork" style titles stay in-font. */
    fun fold(c: Char): Char = when (c) {
        in "ÀÁÂÃÄÅ" -> 'A'
        in "àáâãäå" -> 'a'
        in "ÈÉÊË" -> 'E'
        in "èéêë" -> 'e'
        in "ÌÍÎÏ" -> 'I'
        in "ìíîï" -> 'i'
        in "ÒÓÔÕÖØ" -> 'O'
        in "òóôõöø" -> 'o'
        in "ÙÚÛÜ" -> 'U'
        in "ùúûü" -> 'u'
        'Ç' -> 'C'; 'ç' -> 'c'; 'Ñ' -> 'N'; 'ñ' -> 'n'
        'Ý' -> 'Y'; 'ý', 'ÿ' -> 'y'; 'ß' -> 's'
        '‘', '’' -> '\''; '“', '”' -> '"'
        '–', '—' -> '-'; '…' -> '.'; '·' -> '.'
        else -> c
    }
}
